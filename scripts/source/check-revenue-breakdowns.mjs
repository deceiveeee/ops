#!/usr/bin/env node
/**
 * Whose revenue breakdowns add up, measured on their latest annual reports.
 *
 *   node --env-file=.env.local scripts/source/check-revenue-breakdowns.mjs
 *
 * Runs the reader's own rules (lib/filings/revenue.ts) over each company's
 * newest 10-K data file, fetched the way the reader fetches it, and writes
 * docs/source-audits/studio-revenue-breakdowns.md. The companies are chosen
 * because each tags its breakdowns differently. A rule that works on all of them
 * is not proof it works everywhere; a rule that fails on one is proof it does not.
 *
 * Every request names a contact address, from OPS_SEC_CONTACT, which is never
 * printed or written anywhere.
 */

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pickXbrlFiles, readRevenue } from "../../lib/filings/revenue.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const REPORT = join(ROOT, "docs", "source-audits", "studio-revenue-breakdowns.md");

const COMPANIES = [
  ["ATKR", "The Atkore journey's company: product lines tagged under segments"],
  ["NUE", "An Atkore peer; keeps its labels in its schema, with no label file"],
  ["HUBB", "An Atkore peer; tags a restatement axis beside its breakdowns"],
  ["ETN", "An Atkore peer"],
  ["NVT", "An Atkore peer"],
  ["WLK", "In Atkore's peer set by product"],
  ["AAPL", "Tags a Products subtotal beside the parts it sums"],
  ["NFLX", "Tags its regions under a single product"],
];

const contact = process.env.OPS_SEC_CONTACT?.trim();
if (!contact) throw new Error("Set OPS_SEC_CONTACT, for example: node --env-file=.env.local scripts/source/check-revenue-breakdowns.mjs");
const UA = `Open Portfolio Studio educational research ${contact}`;
const sleep = (ms) => new Promise((done) => setTimeout(done, ms));
let bytesRead = 0;

async function get(url) {
  for (let attempt = 1; attempt <= 4; attempt++) {
    await sleep(700 * attempt);
    const response = await fetch(url, { headers: { "User-Agent": UA, Accept: "*/*" } });
    if (response.ok) {
      const text = await response.text();
      bytesRead += text.length;
      return text;
    }
    if (response.status === 404 || attempt === 4) throw new Error(`${url} answered ${response.status}`);
  }
}

const today = new Date().toLocaleDateString("en-CA");
const listed = Object.values(JSON.parse(await get("https://www.sec.gov/files/company_tickers.json")));
const rows = [];

for (const [ticker, why] of COMPANIES) {
  const match = listed.find((row) => row.ticker === ticker);
  if (!match) {
    rows.push({ ticker, why, error: "not in the SEC's ticker file" });
    continue;
  }
  const cik = String(match.cik_str);
  try {
    const submissions = JSON.parse(await get(`https://data.sec.gov/submissions/CIK${cik.padStart(10, "0")}.json`));
    const recent = submissions.filings.recent;
    const index = recent.form.indexOf("10-K");
    if (index < 0) throw new Error("no 10-K in its recent filings");
    const accession = recent.accessionNumber[index];
    const primary = recent.primaryDocument[index];
    const base = `https://www.sec.gov/Archives/edgar/data/${cik}/${accession.replace(/-/g, "")}/`;
    const names = JSON.parse(await get(`${base}index.json`)).directory.item.map((item) => item.name);
    const files = pickXbrlFiles(names, primary);
    if (!files.instance) throw new Error("no XBRL data file in the filing");
    const instance = await get(base + files.instance);
    const labels = files.labels ? await get(base + files.labels) : "";
    const result = readRevenue(instance, labels);
    rows.push({ ticker, name: submissions.name, why, accession, base, files, result });
    const summary = result.found
      ? result.revenue.breakdowns.map((entry) => `${entry.kind} ${entry.found ? entry.rows.length : "no"}`).join(", ") + `, ${result.revenue.customers.length} customer shares`
      : `not read: ${result.reason}`;
    console.log(`${ticker.padEnd(5)} ${accession} ${summary}`);
  } catch (error) {
    rows.push({ ticker, why, error: error.message });
    console.log(`${ticker.padEnd(5)} FAILED: ${error.message}`);
  }
}

const money = (value) => `$${(value / 1_000_000).toLocaleString("en-US", { maximumFractionDigits: 0 })}m`;
const cell = (entry) => {
  if (!entry) return "—";
  if (!entry.found) return "not shown";
  return `${entry.rows.length} ${entry.rows.length === 1 ? "part" : "parts"}, add up${entry.subtotalsLeftOut.length ? ` (subtotal left out: ${entry.subtotalsLeftOut.join(", ")})` : ""}`;
};

const lines = [
  "# Revenue breakdowns: which add up",
  "",
  "Generated by `scripts/source/check-revenue-breakdowns.mjs`. Do not edit by hand.",
  "",
  `Measured ${today} on each company's newest annual report, with the rules the company-report reader`,
  `uses (\`lib/filings/revenue.ts\`). ${(bytesRead / 1024 / 1024).toFixed(2)} MB of filings were read.`,
  "",
  "A breakdown is shown as shares only when its parts add up to the total revenue the same filing tags,",
  "allowing only for the rounding the filing declares. Where every part together overshoots, the largest set",
  "that adds up is used, if it is the only set of that size and each part left out is the sum of parts kept.",
  "",
  "| Company | Year to | Revenue | Product lines | Regions | Segments | Customer shares |",
  "| --- | --- | ---: | --- | --- | --- | ---: |",
];
for (const row of rows) {
  if (row.error || !row.result.found) {
    lines.push(`| ${row.ticker} | — | — | ${row.error ? `failed: ${row.error}` : `not read: ${row.result.reason}`} | | | |`);
    continue;
  }
  const { revenue } = row.result;
  const kind = (wanted) => revenue.breakdowns.find((entry) => entry.kind === wanted);
  lines.push(
    `| ${row.ticker} | ${revenue.periodEnd} | ${money(revenue.total)} | ${cell(kind("products"))} | ${cell(kind("regions"))} | ${cell(kind("segments"))} | ${revenue.customers.length} |`,
  );
}

lines.push("", "## Each company", "");
for (const row of rows) {
  lines.push(`### ${row.ticker}${row.name ? `, ${row.name}` : ""}`, "", row.why + ".", "");
  if (row.error) {
    lines.push(`Failed: ${row.error}`, "");
    continue;
  }
  lines.push(`10-K \`${row.accession}\`; data file \`${row.files.instance}\`, labels from \`${row.files.labels ?? "none"}\`.`, "");
  if (!row.result.found) {
    lines.push(`Not read: ${row.result.reason}`, "");
    continue;
  }
  for (const entry of row.result.revenue.breakdowns) {
    if (!entry.found) {
      lines.push(`- **${entry.kind}**: not shown. ${entry.reason}`);
      continue;
    }
    lines.push(`- **${entry.kind}**: ${entry.rows.map((part) => `${part.label} ${(part.share * 100).toFixed(1)}%`).join("; ")}`);
  }
  const customers = row.result.revenue.customers;
  lines.push(
    `- **customers**: ${customers.length ? customers.map((c) => `${c.customer} ${(c.share * 100).toFixed(0)}% of ${c.of === "sales" ? "sales" : "receivables"}`).join("; ") : "none tagged as a share of sales or receivables"}`,
    "",
  );
}

writeFileSync(REPORT, lines.join("\n"), "utf8");
console.log(`\n${(bytesRead / 1024 / 1024).toFixed(2)} MB read\nreport  ${REPORT}`);
