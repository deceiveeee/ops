#!/usr/bin/env node
/**
 * How much of Investigate's seven a filing can actually fill.
 *
 *   node scripts/source/check-prefill-coverage.mjs
 *
 * Reads the company facts already cached by `fetch-fundamentals.mjs` and runs
 * the real prefill rules over them, so the answer is measured rather than
 * asserted. Offline: it fetches nothing and fails if the cache is missing.
 *
 * The twelve companies are that script's manifest, chosen because each one
 * breaks something a single definition would assume — a bank, an insurer, a
 * REIT, a utility, a railroad, a loss year. A rule that works on all twelve is
 * not proof it works everywhere, but a rule that fails on one of them is proof
 * it does not.
 *
 * Three defects in total borrowings were found this way on 2026-09-11, each of
 * which had produced a plausible number rather than an error. They are the
 * reason this script exists rather than a one-off check.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/*
 * Node strips types but will not resolve `./metrics` to `./metrics.ts`, and the
 * app source must keep extensionless imports for the bundler. So the extension
 * is supplied here rather than changed there.
 */
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith(".") && !/\.[a-z]+$/.test(specifier) && context.parentURL) {
      const candidate = fileURLToPath(new URL(specifier, context.parentURL)) + ".ts";
      if (existsSync(candidate)) return { url: pathToFileURL(candidate).href, shortCircuit: true };
    }
    return nextResolve(specifier, context);
  },
});

const { sectorFromSic } = await import("../../lib/studio-project/metrics.ts");
const { figuresFromFacts, periodToRead } = await import("../../lib/studio-project/prefill.ts");
const { FIGURES } = await import("../../lib/studio-project/investigate.ts");

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const CACHE = join(ROOT, ".source-cache", "fundamentals");
const REPORT = join(ROOT, "docs", "source-audits", "studio-investigate-prefill.md");
const MANIFEST = join(HERE, "fundamentals-manifest.json");

if (!existsSync(CACHE)) {
  console.error(`No cache at ${CACHE}. Run scripts/source/fetch-fundamentals.mjs first.`);
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
// The local date, so the audit is dated the day the person running it saw.
const today = new Date().toLocaleDateString("en-CA");

/** Find a cached company by ticker, through its cached submissions file. */
function load(ticker, pinnedCik) {
  const subs = [];
  for (const cik of cachedCiks()) {
    const path = join(CACHE, `sub-${cik}.json`);
    if (!existsSync(path)) continue;
    const submissions = JSON.parse(readFileSync(path, "utf8"));
    const tickers = submissions.tickers ?? [];
    if (pinnedCik ? cik === pinnedCik : tickers.includes(ticker)) subs.push({ cik, submissions });
  }
  const found = subs[0];
  if (!found) return null;
  const factsPath = join(CACHE, `facts-${found.cik}.json`);
  if (!existsSync(factsPath)) return null;
  return {
    cik: found.cik,
    name: found.submissions.name,
    sic: String(found.submissions.sic ?? ""),
    sicDescription: found.submissions.sicDescription ?? "",
    facts: JSON.parse(readFileSync(factsPath, "utf8")),
  };
}

function cachedCiks() {
  return readdirSync(CACHE)
    .filter((name) => name.startsWith("sub-") && name.endsWith(".json"))
    .map((name) => name.slice(4, -5));
}

const label = Object.fromEntries(FIGURES.map((figure) => [figure.key, figure.label]));
const rows = [];
const notes = [];

for (const entry of manifest.companies) {
  const company = load(entry.ticker, entry.cik);
  if (!company) { notes.push(`${entry.ticker}: not in the cache`); continue; }

  const sector = sectorFromSic(company.sic);
  const period = periodToRead(company.facts);
  if (!period) { notes.push(`${entry.ticker}: no annual period under us-gaap`); continue; }

  const result = figuresFromFacts(company.facts, sector, period);
  const debt = result.supplied.find((figure) => figure.key === "totalDebt");
  rows.push({
    ticker: entry.ticker,
    name: company.name,
    sic: company.sic,
    sector,
    period,
    filled: result.supplied.length,
    missing: result.missing,
    debt,
  });
}

const full = rows.filter((row) => row.filled === 7).length;
const money = (value) => `$${(value / 1e6).toLocaleString("en-US", { maximumFractionDigits: 0 })}m`;

const lines = [
  "# Filling Investigate's seven figures from a filing",
  "",
  "Generated by `scripts/source/check-prefill-coverage.mjs`. Do not edit by hand.",
  "",
  `Measured ${today} against cached SEC company facts for ${rows.length} companies, the manifest`,
  "`fetch-fundamentals.mjs` uses. Each is there because it breaks something a single definition",
  "would assume.",
  "",
  "## What filled",
  "",
  `${full} of ${rows.length} companies gave all seven figures.`,
  "",
  "| Company | SIC | Shape | Period | Filled | Not tagged |",
  "| --- | --- | --- | --- | ---: | --- |",
  ...rows.map((row) =>
    `| ${row.ticker} ${row.name} | ${row.sic} | ${row.sector} | ${row.period} | ${row.filled}/7 | ` +
    `${row.missing.length ? row.missing.map((figure) => label[figure.key].toLowerCase()).join(", ") : "—"} |`),
  "",
  "A figure that is not tagged stays an empty box with the reason beside it. None becomes a zero,",
  "and none is derived from a concept that means something else.",
  "",
  "## Total borrowings, which is the one that is built rather than read",
  "",
  "Investigate's box promises money owed to lenders, excluding leases. No single XBRL tag carries",
  "that for every filer, so it is assembled — and three ways of assembling it wrongly were measured",
  "here, each producing a plausible number rather than an error.",
  "",
  "| Company | Total | From |",
  "| --- | ---: | --- |",
  ...rows.map((row) =>
    `| ${row.ticker} | ${row.debt ? money(row.debt.value) : "not supplied"} | ` +
    `${row.debt ? row.debt.concepts.join(" + ") : "no lease-free borrowing tag is filed"} |`),
  "",
  "The rules, each checked against the table above:",
  "",
  "1. **A combined tag is complete.** `DebtLongtermAndShorttermCombinedAmount` already holds both,",
  "   so nothing is added to it. Verizon's 158,150 is 139,532 + 18,177 + 441; adding its short-term",
  "   borrowings on top counted $441m twice.",
  "2. **`LongTermDebt` includes the instalment due this year.** Verified where all three appear:",
  "   Atkore 761 = 757 + 4, Microsoft 40,294 = 31,067 + 9,227, NVIDIA 8,468 = 7,469 + 999. Short-term",
  "   borrowing is separate and is added.",
  "3. **A noncurrent tag does not.** Where `LongTermDebt` is absent, `LongTermDebtCurrent` is added",
  "   back. Taking the noncurrent tag alone understated Costco by $75m, Pfizer by $3.0bn and NextEra",
  "   by $3.5bn.",
  "4. **Short-term borrowing: the total if there is one, else its parts.** `ShortTermBorrowings` is",
  "   used alone where filed. Otherwise commercial paper, other short-term borrowings and notes",
  "   payable are summed, and a part tagged as zero is left out of the provenance because it added",
  "   nothing — Pfizer files commercial paper of zero beside $157m of other short-term borrowing.",
  "5. **Lease-inclusive tags are refused.** Exxon files only",
  "   `LongTermDebtAndCapitalLeaseObligations`, which bundles $2.7bn of finance leases in with the",
  "   debt. Supplying it would mean something different from the box's own definition and from every",
  "   other company's figure, so the box stays empty and says why.",
  "",
  "## What this cannot do",
  "",
  "- **US GAAP only.** A foreign issuer filing its 20-F under IFRS tags under `ifrs-full`, and",
  "  nothing resolves. SAP returns a message saying so rather than an empty form.",
  "- **Operating profit is often absent.** Exxon and Pfizer tag no `OperatingIncomeLoss`, and it is",
  "  not derived from total costs: that subtraction yields operating income wearing the name of",
  "  gross profit. For a bank or an insurer the quantity is not defined, and Investigate already",
  "  declines to compute a return on capital for either.",
  "- **Company facts can lag a filing.** TSMC's FY2025 20-F was on EDGAR and tagged while company",
  "  facts still ended at 2024-12-31 (measured 2026-09-10). The period read is the newest company",
  "  facts holds, and the filing named is the one that reported it.",
  "- **Rule 4 could overstate.** If a company files both `ShortTermBorrowings` and its components,",
  "  only the total is used; if it files components that overlap each other, they would be summed.",
  "  None of the twelve does, and the provenance names every tag added so the sum can be checked",
  "  against the balance sheet.",
  "",
];

if (notes.length) lines.push("## Not measured", "", ...notes.map((note) => `- ${note}`), "");

writeFileSync(REPORT, lines.join("\n"), "utf8");
console.log(`${full}/${rows.length} companies gave all seven figures`);
for (const row of rows) {
  console.log(`  ${row.ticker.padEnd(5)} ${row.period} ${row.filled}/7 ${row.missing.map((f) => f.key).join(",")}`);
}
console.log(`\nreport  ${REPORT}`);
